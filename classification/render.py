"""Render docs/classification.md from findings.json so the table cannot drift.

    python -m classification.render            # rewrite the document
    python -m classification.render --check    # exit 1 if the document is stale
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

from classification.cvss31 import score

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "classification" / "findings.json"
TARGET = ROOT / "docs" / "classification.md"


def render() -> str:
    data = json.loads(SOURCE.read_text(encoding="utf-8"))
    names = data["mitigation_names"]
    out = [
        "# Finding classification",
        "",
        "<!-- Generated by `python -m classification.render` from classification/findings.json. Do not edit by hand. -->",
        "",
        "Every finding is classified against public taxonomies and scored with the CVSS v3.1 base",
        "formula. Scores are computed by [`classification/cvss31.py`](../classification/cvss31.py)",
        "from the vector string; CI fails if this page and the source data disagree.",
        "",
        f"> **Scoring assumption.** {data['scoring_assumption']}",
        "",
        "## Summary",
        "",
        "| ID | Weakness | CWE | OWASP | CVSS v3.1 | Severity | ATT&CK | Detection |",
        "| --- | --- | --- | --- | ---: | --- | --- | --- |",
    ]
    for f in data["findings"]:
        s = score(f["cvss"])
        techniques = ", ".join(t["id"] for t in f["attack"])
        rule = Path(f["detection"]).name
        out.append(
            f"| [{f['id']}](../writeups/finding-{f['id']}.md) | {f['title']} | {', '.join(f['cwe'])} "
            f"| {', '.join(f['owasp'])} | {s.base:.1f} | {s.severity} | {techniques} "
            f"| [`{rule}`](../{f['detection']}) |"
        )
    out += ["", "## Score derivation", "",
            "`ISS = 1 - (1-C)(1-I)(1-A)`; `Impact = 6.42 x ISS` when scope is unchanged, or",
            "`7.52 x (ISS - 0.029) - 3.25 x (ISS - 0.02)^15` when changed;",
            "`Exploitability = 8.22 x AV x AC x PR x UI`; the base score is the spec-defined round-up of",
            "`Impact + Exploitability` (multiplied by 1.08 when scope is changed), capped at 10.", ""]
    for f in data["findings"]:
        s = score(f["cvss"])
        total = s.impact + s.exploitability
        changed = "/S:C/" in f["cvss"]
        pre = f"1.08 x ({s.impact:.2f} + {s.exploitability:.2f}) = {1.08 * total:.2f}" if changed \
            else f"{s.impact:.2f} + {s.exploitability:.2f} = {total:.2f}"
        out += [
            f"### FINDING-{f['id']} — {s.base:.1f} ({s.severity})",
            "",
            f"`{f['cvss']}`",
            "",
            f"- ISS {s.iss:.3f}, impact {s.impact:.2f}, exploitability {s.exploitability:.2f}; {pre}, rounded up to **{s.base:.1f}**.",
            f"- Rationale: {f['cvss_rationale']}",
            "- ATT&CK: " + "; ".join(f"{t['id']} {t['name']} ({t['tactic']})" for t in f["attack"]) + ".",
            "- ATT&CK mitigations: " + "; ".join(f"{m} {names[m]}" for m in f["mitigations"]) + ".",
            f"- Evidence: exploit test `{f['poc']}`; fix test `{f['regression']}`.",
            "",
        ]
    out += [
        "## Two severity labels",
        "",
        "Each write-up keeps its original `Severity (lab)` line, a lab-relative judgement about the",
        "demo assets. The CVSS score beside it is the standardized rating and is the one to compare",
        "across findings; the two can differ (FINDING-001 is High in lab terms and 6.5 Medium in CVSS",
        "because it needs an authenticated account).",
        "",
        "## Taxonomy editions",
        "",
        "OWASP identifiers refer to the OWASP Top 10:2025 (where SSRF is part of A01 Broken Access",
        "Control) and the OWASP API Security Top 10 2023. ATT&CK identifiers refer to Enterprise ATT&CK.",
        "",
        "## Reading the ATT&CK column",
        "",
        "MITRE ATT&CK describes adversary behaviour, not software weakness classes, so the mapping is",
        "an analyst judgement about which technique an operator would be performing when using each",
        "flaw. CWE is the authoritative weakness identifier. T1606.001 names web cookies; the fixture",
        "carries its token in a header, and the sub-technique is used as the closest published match.",
        "",
    ]
    return "\n".join(out)


def main(argv: list[str]) -> int:
    text = render()
    if "--check" in argv:
        current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
        if current != text:
            print("docs/classification.md is stale; run python -m classification.render", file=sys.stderr)
            return 1
        return 0
    TARGET.write_text(text, encoding="utf-8")
    print(f"wrote {TARGET.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
